"""Administrative port. Concrete adapters must enforce ACL and atomic revisions in IRIS."""
from typing import Any, Protocol

class GatewayError(Exception):
    """Sanitized public error, never native exception text."""
    def __init__(self, code: str, message: str, status: int = 422):
        super().__init__(message)
        self.code, self.message, self.status = code, message, status

class IrisGateway(Protocol):
    def detect_capabilities(self, *, principal: str) -> dict[str, Any]: ...
    def get_settings(self, *, principal: str) -> dict[str, Any]: ...
    def save_settings(self, payload: dict, *, principal: str) -> dict[str, Any]: ...
    def list_productions(self, *, principal: str) -> list[dict]: ...
    def list_templates(self, *, principal: str) -> list[dict]: ...
    def list_workflows(self, production: str, *, principal: str) -> list[dict]: ...
    def get_workflow(self, workflow_id: str, *, principal: str) -> dict: ...
    def create_managed_workflow(self, template_id: str, production: str, *, principal: str) -> dict: ...
    def insert_decision_slot(self, workflow_id: str, expected_revision: int, *, principal: str) -> dict: ...
    def preview_input(self, workflow_id: str, binding: dict, example: dict, *, principal: str) -> dict: ...
    def rollback_workflow(self, workflow_id: str, release_id: str, expected_revision: int, *, principal: str) -> dict: ...
    def list_agents(self, *, principal: str) -> list[dict]: ...
    def save_agent_revision(self, agent_id: str, definition: dict, base_revision: int, *, principal: str) -> dict: ...
    def save_bindings(self, workflow_id: str, bindings: list[dict], expected_revision: int, *, principal: str) -> dict: ...
    def save_binding(self, binding_id: str, payload: dict, expected_revision: int, *, principal: str) -> dict: ...
    def list_toolsets(self, *, principal: str) -> list[dict]: ...
    def validate_workflow(self, workflow_id: str, *, principal: str) -> dict: ...
    def preview_publish(self, workflow_id: str, *, principal: str) -> dict: ...
    def publish_workflow(self, workflow_id: str, base_hash: str, revision: int, approval_ref: str, *, idempotency_key: str, principal: str) -> dict: ...
    def list_releases(self, workflow_id: str, *, principal: str) -> list[dict]: ...
    def submit_test_message(self, release_id: str, payload: dict, *, principal: str) -> str: ...
    def get_run(self, execution_id: str, *, principal: str) -> dict: ...
